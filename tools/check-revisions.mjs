import assert from 'node:assert/strict';
import fs from 'node:fs';
import {clone,makeRevision,changeRequest,objectChanges,validateDocument} from '../model.js';
import {LibraryClient,validateCatalog} from '../library-client.js';
const catalog=JSON.parse(fs.readFileSync('library/catalog.json'));
const referenceEntry=catalog.modules.find(m=>m.category==='平原')??catalog.modules[0];
const ref=JSON.parse(fs.readFileSync(referenceEntry.file));
const edit=makeRevision(ref);
assert.notEqual(edit.id,ref.id);
assert.deepEqual(changeRequest(edit).target.moduleId,ref.source.moduleId);
assert.equal(changeRequest(edit).preserveModuleIdentity,true);
assert.equal(changeRequest(edit).applicationStatus,'not_applied');
edit.objects[0].x+=12;const removed=edit.objects.pop();
edit.objects.push({...clone(edit.objects[0]),id:'new-object'});
const changes=objectChanges(edit);
assert.equal(changes.added.length,1);assert.equal(changes.removed[0],removed.id);assert.equal(changes.modified.length,1);
assert.deepEqual(ref.objects,JSON.parse(fs.readFileSync(referenceEntry.file)).objects);
const variant=makeRevision(ref,'new_variant');assert.equal(changeRequest(variant).target,null);assert.equal(changeRequest(variant).derivedFrom.moduleId,ref.source.moduleId);assert.equal(changeRequest(variant).preserveModuleIdentity,false);
assert.equal(validateDocument(JSON.parse(JSON.stringify(edit))).intent.operation,'modify_existing');
const before='1'.repeat(40),after='2'.repeat(40),editor='3'.repeat(40);
const old={...clone(catalog),sourceCommit:before},fresh={...clone(catalog),sourceCommit:after};
const urls=[];
const client=new LibraryClient('https://example.com/map-edit/',async url=>{urls.push(url);const data=url.includes('gunman-rush/commits')?{sha:after}:url.includes('map-edit/commits')?{sha:editor}:url.includes('raw.githubusercontent.com')?fresh:old;return new Response(JSON.stringify(data));});
await client.load();const result=await client.checkUpdate();assert(result.isLatest);assert(result.changed);assert(client.baseURL.includes(editor));assert.equal(client.catalog.sourceCommit,after);assert(urls.some(u=>u.includes('/'+editor+'/library/catalog.json')));
const broken=clone(fresh);broken.modules[0].file='https://evil.example/steal';assert.throws(()=>validateCatalog(broken));
const fail=new LibraryClient('https://example.com/map-edit/',async url=>url.includes('/commits/')?new Response(JSON.stringify({sha:after})):new Response(JSON.stringify(broken)));
fail.catalog=old;await assert.rejects(()=>fail.checkUpdate());assert.equal(fail.catalog,old);
const limit=new LibraryClient('https://example.com/map-edit/',async()=>new Response('',{status:403}));limit.catalog=old;await assert.rejects(()=>limit.checkUpdate(),/限额/);assert.equal(limit.catalog,old);
console.log('Revision identity, variant separation, object diffs, immutable library updates and failed-update preservation passed.');
